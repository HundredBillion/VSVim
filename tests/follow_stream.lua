local project = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h')
vim.opt.runtimepath:prepend(project)
if vim.env.VSVIM_FOLLOW_SOURCE then vim.opt.runtimepath:prepend(vim.env.VSVIM_FOLLOW_SOURCE) end
local root = vim.fn.tempname()
vim.fn.mkdir(root, 'p')
root = vim.uv.fs_realpath(root)
vim.cmd.cd(root)
local path = root .. '/methods.py'
vim.fn.writefile({'saved = True'}, path)
local follow = require('vsvim.follow')
follow.setup()
vim.cmd('VSVimFollowOn')
assert(vim.wait(5000, function() return follow.status().ready end))
assert(follow.preview({path=path, text='def greeting():\n    return "he', cursor={2,13}}))
vim.g.sprite_follow_native=true
assert(follow.statusline():find('LIVE',1,true),'native footer reports live preview')
vim.g.sprite_follow_native=false
assert(vim.api.nvim_get_current_line() == '    return "he', 'incoming text is displayed immediately')
assert(vim.deep_equal(vim.api.nvim_win_get_cursor(0), {2,13}), 'cursor uses actual Neovim column')
assert(not vim.bo.modifiable and not vim.bo.modified, 'preview is read-only')
assert(vim.fn.readfile(path)[1] == 'saved = True', 'preview does not write to disk')
local preview = vim.api.nvim_get_current_buf()
vim.cmd('VSVimFollowOff')
assert(not follow.native_snapshot().enabled, 'native icon sees Off')
assert(not follow.preview({path=path, text='ignored', cursor={1,0}}))
assert(vim.api.nvim_buf_get_lines(preview, 0, -1, false)[2] == '    return "he', 'Off freezes display')
_G.VSVimFollowClick(0, 1, 'l')
assert(follow.native_snapshot().enabled, 'statusline click enables Follow')
assert(follow.preview({path=path, text='def greeting():\n    return "hello"', cursor={2,18}}))
assert(vim.api.nvim_win_get_cursor(0)[2] == 17, 'end column is clamped by Neovim')
vim.wait(250, function() return false end)
assert(follow.status().enabled, 'Follow does not mistake its updates for user movement')
vim.api.nvim_win_set_cursor(0, {1,0})
assert(not follow.preview({path=path, text='ignored', cursor={1,0}}))
assert(not follow.status().enabled, 'manual cursor movement disables Follow')
vim.fn.maparg('<leader>af', 'n', false, true).callback()
assert(follow.status().enabled, 'keyboard toggle enables Follow')
assert(follow.preview({path=path, text='saved preview\n', cursor={1,5}}))
assert(vim.bo.endofline and vim.api.nvim_buf_line_count(0) == 1, 'terminal newline is preserved without adding a blank line')
vim.fn.writefile({'agent saved'}, path)
vim.wait(800, function() return false end)
assert(vim.api.nvim_get_current_buf() == preview and vim.api.nvim_get_current_line() == 'saved preview', 'disk watcher cannot interrupt live preview')
follow.finish_preview()
vim.fn.writefile({'next disk edit'}, path)
assert(vim.wait(5000, function()
  return vim.api.nvim_buf_get_name(0) == path and vim.api.nvim_get_current_line() == 'next disk edit'
end), 'filesystem Follow resumes after stream finishes')
assert(vim.api.nvim_get_current_line() == 'next disk edit')
assert(follow.preview({path=path, text='final line\n', cursor={2,0}}), 'newline-boundary cursor is accepted')
assert(vim.deep_equal(vim.api.nvim_win_get_cursor(0), {1,9}), 'newline boundary displays at end of final line')
local before = vim.api.nvim_get_current_buf()
assert(not follow.preview({path=root .. '/../outside.py', text='outside', cursor={1,0}}))
assert(not follow.preview({path=path, text='invalid', cursor={99,0}}))
assert(not follow.preview({path=path, text='binary\0content', cursor={1,0}}))
local linked = root .. '/linked.py'
assert(vim.uv.fs_symlink(path, linked))
assert(not follow.preview({path=linked, text='alias', cursor={1,0}}))
assert(vim.api.nvim_get_current_buf() == before and vim.api.nvim_get_current_line() == 'final line', 'rejected updates leave preview intact')
follow.finish_preview()
assert(vim.api.nvim_buf_get_name(0) == path, 'finishing returns to saved editable file')
assert(follow.preview({path=path, text='partial preview', cursor={1,5}}))
vim.fn.writefile({'final saved file'}, path)
vim.wait(800, function() return false end)
follow.finish_preview()
assert(vim.api.nvim_get_current_line() == 'final saved file' and vim.bo.buftype == '', 'finishing reconciles final save received during preview')
local tree = vim.api.nvim_create_buf(false, true)
vim.bo[tree].filetype = 'svgtree'
vim.cmd('vsplit')
vim.api.nvim_win_set_buf(0, tree)
follow.set_enabled(true)
assert(follow.preview({path=root .. '/new.py', text='print("new")', cursor={1,5}}))
assert(vim.api.nvim_win_get_buf(0) == tree, 'stream does not replace explorer buffer')
assert(vim.api.nvim_buf_get_lines(tree, 0, -1, false)[1] == '', 'explorer contents are untouched')
follow.set_enabled(false)
vim.cmd('close')
follow.set_enabled(true)
for i=1,31 do
  assert(follow.preview({path=root .. '/preview' .. i .. '.py', text='snapshot '..i, cursor={1,0}}))
end
local count = 0
for _, buf in ipairs(vim.api.nvim_list_bufs()) do
  if vim.api.nvim_buf_get_name(buf):match('^follow://') then count = count + 1 end
end
assert(count == 1, 'stream reuses one preview buffer across files')
assert(vim.fn.undotree().seq_last == 0, 'stream snapshots do not accumulate undo history')
follow.set_enabled(false)
vim.cmd('edit ' .. vim.fn.fnameescape(path))
vim.api.nvim_buf_set_lines(0, 0, -1, false, {'unsaved developer work'})
follow.set_enabled(true)
assert(not follow.preview({path=path, text='agent text', cursor={1,0}}))
assert(not follow.status().enabled, 'unsaved target conflict disables Follow')
assert(vim.api.nvim_get_current_line() == 'unsaved developer work', 'unsaved text survives conflict')
follow.set_enabled(false)
vim.bo.modified = false
local outside = vim.fn.tempname()
vim.fn.writefile({'outside project'}, outside)
local final = root .. '/completion.py'
vim.fn.writefile({'original'}, final)
follow.set_enabled(true)
assert(follow.preview({path=final, text='preview', cursor={1,0}}))
assert(vim.uv.fs_unlink(final))
assert(vim.uv.fs_symlink(outside, final))
follow.finish_preview()
assert(not follow.status().enabled, 'completion rejects a target replaced by a symlink')
assert(vim.api.nvim_get_current_line() == 'preview', 'outside project content is never opened')
vim.fn.delete(outside)
vim.fn.delete(root, 'rf')
print('VSVim Follow stream passed')
vim.cmd('qa!')
