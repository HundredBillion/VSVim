local project = vim.fn.fnamemodify(debug.getinfo(1,'S').source:sub(2), ':p:h:h')
vim.opt.runtimepath:prepend(project)
if vim.env.VSVIM_FOLLOW_SOURCE then vim.opt.runtimepath:prepend(vim.env.VSVIM_FOLLOW_SOURCE) end
local root = vim.fn.tempname()
vim.fn.mkdir(root,'p')
root = vim.uv.fs_realpath(root)
local known = root .. '/known.lua'
local unknown = root .. '/unknown.lua'
vim.fn.writefile({'original'},known)
vim.fn.writefile({'unopened'},unknown)
vim.cmd.cd(root)
vim.cmd.edit(known)
local follow = require('vsvim.follow')
follow.setup()
vim.cmd('VSVimFollowOn')
assert(vim.wait(3000,function() return follow.status().ready end))
assert(follow.status().capability=='waiting','waiting state is visible')
vim.fn.writefile({'changed externally'},known)
assert(vim.wait(3000,function() return vim.api.nvim_get_current_line()=='changed externally' end),
  'known-file fallback follows a save')
vim.cmd.enew()
follow.set_enabled(true)
vim.fn.writefile({'unknown changed'},unknown)
vim.wait(700,function() return false end)
assert(vim.api.nvim_buf_get_name(0)=='','unreported unopened file is outside fallback scope')
follow.set_enabled(false)
vim.cmd.edit(known)
vim.api.nvim_buf_set_lines(0,0,-1,false,{'developer unsaved work'})
follow.set_enabled(true)
vim.fn.writefile({'external conflict'},known)
assert(vim.wait(3000,function() return not follow.status().enabled end),
  'external write to an unsaved buffer disengages Follow')
assert(vim.api.nvim_get_current_line()=='developer unsaved work','unsaved buffer is preserved')
vim.bo.modified=false
vim.fn.delete(root,'rf')
print('VSVim known-file Follow passed')
vim.cmd('qa!')
