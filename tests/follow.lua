local project = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h')
vim.opt.runtimepath:prepend(project)
local root = vim.fn.tempname()
vim.fn.mkdir(root .. '/src', 'p')
root = vim.uv.fs_realpath(root)
vim.fn.writefile({'one', 'two', 'three'}, root .. '/src/main.lua')
vim.cmd.cd(root)
local follow = require('vsvim.follow')
follow.setup()
follow.set_enabled(true)
assert(vim.wait(5000, function() return follow.status().ready end), 'initial snapshot completes')
assert(vim.api.nvim_buf_get_name(0) == '', 'activation does not open existing files')
vim.fn.writefile({'one', 'two', 'changed'}, root .. '/src/main.lua')
assert(vim.wait(5000, function() return vim.api.nvim_buf_get_name(0) == root .. '/src/main.lua' end), 'external edit opens unopened nested file: ' .. vim.inspect(follow.status()) .. ' buffer=' .. vim.api.nvim_buf_get_name(0))
assert(vim.api.nvim_win_get_cursor(0)[1] == 3, 'cursor follows changed line')

local function settle() vim.wait(700, function() return false end, 20) end
local function ready()
  follow.set_enabled(true)
  assert(vim.wait(5000, function() return follow.status().ready end), 'snapshot ready')
end
local function changed(lines, row)
  vim.fn.writefile(lines, root .. '/src/main.lua')
  assert(vim.wait(5000, function()
    return vim.api.nvim_buf_get_lines(0,0,-1,false)[#lines] == lines[#lines]
      and vim.api.nvim_win_get_cursor(0)[1] == row
  end), 'external content reloads and cursor follows')
end
settle()
assert(follow.status().enabled, 'follow navigation does not disable itself')
changed({'ONE', 'two', 'THREE'}, 3)
assert(follow.status().enabled, 'reload does not disable Follow')
vim.fn.writefile({'ONE','two','atomic'}, root .. '/replacement')
assert(vim.uv.fs_rename(root .. '/replacement', root .. '/src/main.lua'))
assert(vim.wait(5000,function() return vim.api.nvim_get_current_line() == 'atomic' end), 'atomic replacement follows')
vim.api.nvim_win_set_cursor(0,{1,0})
assert(vim.wait(1000,function() return not follow.status().enabled end), 'manual navigation disables Follow')
ready()
vim.cmd('write')
settle()
assert(follow.status().enabled and vim.api.nvim_win_get_cursor(0)[1] == 1, 'own save does not jump')
changed({'ONE','two','external immediately after save'},3)
vim.api.nvim_buf_set_lines(0,0,1,false,{'unsaved developer text'})
ready()
vim.fn.writefile({'conflicting external text'}, root .. '/src/main.lua')
assert(vim.wait(5000,function() return not follow.status().enabled end), 'unsaved target disables Follow')
assert(vim.api.nvim_buf_get_lines(0,0,1,false)[1] == 'unsaved developer text', 'unsaved text survives')
assert(follow.status().reason:find('unsaved',1,true), 'conflict reason visible')
vim.bo.modified=false
vim.cmd('enew')
ready()
vim.fn.mkdir(root .. '/node_modules', 'p')
vim.fn.writefile({'ignored dependency'},root .. '/node_modules/test.lua')
local binary = assert(io.open(root .. '/binary','wb')); binary:write('binary\0bytes'); binary:close()
settle()
assert(vim.api.nvim_buf_get_name(0) == '', 'generated and binary files ignored')
vim.fn.mkdir(root .. '/new/nested','p')
vim.fn.writefile({'new file'},root .. '/new/nested/file.lua')
assert(vim.wait(5000,function() return vim.api.nvim_get_current_line() == 'new file' end), 'new directory and file followed')
assert(vim.api.nvim_win_get_cursor(0)[1] == 1,'new file starts at line one')
follow.set_enabled(false)
local last = vim.api.nvim_buf_get_name(0)
vim.fn.writefile({'disabled'},root .. '/disabled.lua')
settle()
assert(vim.api.nvim_buf_get_name(0)==last,'disabled Follow never jumps')
local other = vim.fn.tempname()
vim.fn.mkdir(other,'p')
other = vim.uv.fs_realpath(other)
vim.fn.writefile({'existing'},other .. '/other.lua')
follow.set_root(other)
ready()
assert(vim.api.nvim_buf_get_name(0)==last,'changing root does not open baseline files')
vim.fn.writefile({'outside'},root .. '/outside.lua')
settle()
assert(vim.api.nvim_buf_get_name(0)==last,'outside-root writes ignored')
vim.fn.writefile({'follow other root'},other .. '/other.lua')
assert(vim.wait(5000,function() return vim.api.nvim_get_current_line()=='follow other root' end),'new root follows')
follow.set_enabled(false)
local gitroot = vim.fn.tempname()
vim.fn.mkdir(gitroot,'p')
gitroot = vim.uv.fs_realpath(gitroot)
assert(vim.system({'git','init','-q',gitroot}):wait().code==0)
vim.fn.writefile({'ignored/'},gitroot .. '/.gitignore')
vim.fn.writefile({'baseline'},gitroot .. '/tracked.lua')
follow.set_root(gitroot)
ready()
local before = vim.api.nvim_buf_get_name(0)
vim.fn.mkdir(gitroot .. '/ignored','p')
vim.fn.writefile({'ignored'},gitroot .. '/ignored/test.lua')
assert(vim.uv.fs_symlink(other,gitroot .. '/linked'))
vim.fn.writefile({'symlink outside'},other .. '/outside.lua')
settle()
assert(vim.api.nvim_buf_get_name(0)==before,'Git ignored files and external symlink excluded')
vim.fn.writefile({'new untracked'},gitroot .. '/untracked.lua')
assert(vim.wait(5000,function() return vim.api.nvim_get_current_line()=='new untracked' end),'Git untracked file follows')
follow.set_enabled(false)
vim.fn.delete(gitroot,'rf')
vim.fn.delete(other,'rf')
vim.fn.delete(root, 'rf')
print('VSVim Follow passed')
vim.cmd('qa!')
