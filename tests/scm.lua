local root = vim.fn.tempname()
vim.fn.mkdir(root, 'p')
assert(vim.system({'git', '-C', root, 'init', '-b', 'main'}):wait().code == 0)
vim.fn.writefile({'return true'}, root .. '/review.lua')
vim.cmd.cd(root)
require('svgtree').setup({ renderer = 'terminal' })
require('svgtree').open(root)
local function present(ft)
  for _, win in ipairs(vim.api.nvim_list_wins()) do
    if vim.bo[vim.api.nvim_win_get_buf(win)].filetype == ft then return win end
  end
end
local function mapped(key)
  local map = vim.fn.maparg(key, 'n', false, true)
  assert(type(map.callback) == 'function', key)
  map.callback()
end
mapped('<leader>gs')
assert(vim.wait(5000, function() return present('scm') end), 'SCM opens from bundled mapping')
assert(not present('svgtree'), 'SCM closes explorer')
assert(vim.wait(5000, function()
  local buf = vim.api.nvim_win_get_buf(present('scm'))
  return table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), '\n'):find('review.lua', 1, true)
end), 'bundled SCM lists real changes')
assert(require('vsvim.appearance').tabline():find('SOURCE CONTROL', 1, true))
vim.api.nvim_set_current_win(present('scm'))
mapped('<Esc>')
vim.cmd.cd(vim.env.VSVIM_ROOT)
mapped('<leader>e')
assert(vim.wait(3000, function() return present('svgtree') and not present('scm') end), 'explorer handoff works')
assert(require('svgtree').root() == vim.uv.fs_realpath(root), 'handoff preserves SCM root after cwd changes')
require('svgtree').close()
assert(not package.loaded.snacks)
vim.cmd.cd(vim.env.VSVIM_ROOT)
vim.fn.delete(root, 'rf')
print('VSVim SCM passed')
